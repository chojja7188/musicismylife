const {readFileSync} = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = readFileSync('index.html','utf8');
const code = html.match(/function spectrumTarget[\s\S]*?(?=function wrap)/)?.[0];
assert.ok(code, '스펙트럼 반응 함수');
const box={N:48,lvl:new Float32Array(48)}; vm.createContext(box); vm.runInContext(code,box);
assert.equal(box.spectrumTarget(()=>-Infinity,2,8),0,'무음은 0');
const quiet=box.spectrumTarget(()=>-55,2,8), loud=box.spectrumTarget(()=>-25,2,8);
assert.ok(quiet>0 && loud>quiet && loud<.7,'일반적인 큰 소리에도 여유');
const isolated=box.spectrumTarget(i=>i===2 ? -12 : -72,2,12);
assert.ok(isolated<.3,'한 주파수만 커도 대역 전체가 꽉 차지 않음');
assert.ok(box.spectrumTarget(()=>0,2,8)<=.9,'최대치에도 화면 여유');
box.bands(()=>-25); const first=box.lvl[0]; box.bands(()=>-Infinity);
assert.ok(box.lvl[0]<first && box.lvl[0]>0,'잔상은 서서히 내려감');
const layout=html.match(/function outroLayout[\s\S]*?(?=function outro\()/)?.[0];
assert.ok(layout,'아웃트로 배치 함수'); vm.runInContext(layout,box);
assert.equal(box.outroLayout(2).h,box.outroLayout(5).h,'5곡 기준 고정 행 크기');
assert.ok(box.outroLayout(8).h*8<=1250,'5곡 넘으면 전체 표시');
console.log('스펙트럼 여유·반응·감쇠·5곡 배치 통과');
